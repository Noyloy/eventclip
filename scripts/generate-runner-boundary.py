#!/usr/bin/env python3
"""Preserve shared app ABI referenced by every cached runner-exclusive runtime artifact.
No jar copying, no new dependency, no blanket AndroidX/Kotlin package keep.
"""
import io,json,re,struct,zipfile,hashlib
from pathlib import Path
r=Path(__file__).resolve().parents[1]
def classes(path):
 out={}
 with zipfile.ZipFile(path) as z:
  if path.endswith('.aar'):
   jars=[n for n in z.namelist() if n=='classes.jar' or n.startswith('libs/') and n.endswith('.jar')]
   for n in jars:
    with zipfile.ZipFile(io.BytesIO(z.read(n))) as j:out.update({v[:-6]:j.read(v) for v in j.namelist() if v.endswith('.class') and not v.startswith('META-INF/')})
  else:out={v[:-6]:z.read(v) for v in z.namelist() if v.endswith('.class') and not v.startswith('META-INF/')}
 return out

def refs(data):
 # JVM constant-pool Class entries plus field/method/signature descriptor strings.
 count=struct.unpack_from('>H',data,8)[0];off=10;i=1;utf={};indices=[]
 while i<count:
  tag=data[off];off+=1
  if tag==1:
   n=struct.unpack_from('>H',data,off)[0];off+=2;utf[i]=data[off:off+n].decode('utf8','replace');off+=n
  elif tag==7:indices.append(struct.unpack_from('>H',data,off)[0]);off+=2
  elif tag in (3,4,9,10,11,12,17,18):off+=4
  elif tag in (5,6):off+=8;i+=1
  elif tag in (8,16,19,20):off+=2
  elif tag==15:off+=3
  else:raise ValueError(tag)
  i+=1
 out={utf[i] for i in indices if not utf[i].startswith('[')}
 for s in utf.values():out.update(re.findall(r'L([A-Za-z0-9_$/]+)[;<]',s))
 return out
cp=json.loads((r/'reports/vc7/classpaths.json').read_text());app=cp['releaseRuntimeClasspath'];test=cp['releaseAndroidTestRuntimeClasspath'];appModules={a['module'] for a in app}
appClasses={};origin={}
for a in app:
 if a['file'].endswith(('.jar','.aar')):
  c=classes(a['file']);appClasses.update(c);origin.update({n:a['module'] for n in c})
exclusive=[a for a in test if a['module'] not in appModules];references={};allrefs=set()
for a in exclusive:
 if a['file'].endswith(('.jar','.aar')):
  c=classes(a['file']);rs=set().union(*(refs(b) for b in c.values())) if c else set();allrefs|=rs
  references[a['module']]={'classes':len(c),'sharedReferences':sorted(rs&appClasses.keys()),'sha256':hashlib.sha256(Path(a['file']).read_bytes()).hexdigest()}
ownRoot=r/'app/android/app/build/tmp/kotlin-classes/releaseAndroidTest'
ownClasses=sorted(ownRoot.rglob('*.class'));assert ownClasses,'Compile release instrumentation before generating boundary'
for p in ownClasses:allrefs|=refs(p.read_bytes())
references['instrumentation-owned-bytecode']={'classes':len(ownClasses),'sharedReferences':sorted(set().union(*(refs(p.read_bytes()) for p in ownClasses))&appClasses.keys()),'hashes':{str(p.relative_to(ownRoot)):hashlib.sha256(p.read_bytes()).hexdigest() for p in ownClasses}}
boundary=sorted(allrefs&appClasses.keys());assert 'androidx/tracing/Trace' in boundary
rules='# Generated by scripts/generate-runner-boundary.py from cached app/test runtime graphs.\n# Exact shared ABI referenced by runner-exclusive transitives; preserve names+members.\n'+''.join('-keep class '+n.replace('/','.')+' { *; }\n' for n in boundary)
(r/'app/android/app/proguard-product-runner-boundary.pro').write_text(rules)
(r/'reports/vc7/runner-boundary.json').write_text(json.dumps({'scope':'All runner-exclusive resolved runtime artifacts vs app original classes; preserves exact classes/members across independently shrunk APKs','runnerExclusiveArtifacts':references,'sharedClassCount':len(boundary),'sharedClasses':{n:origin[n] for n in boundary}},indent=2))
print('Exact shared ABI classes',len(boundary));print('Runner-exclusive artifacts',list(references))
